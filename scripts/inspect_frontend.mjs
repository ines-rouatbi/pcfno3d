import { chromium } from '@playwright/test';
import { mkdir, writeFile } from 'node:fs/promises';
const out = 'output/redesign';
await mkdir(out, {recursive: true});
const browser = await chromium.launch({channel: 'chrome', headless: true});
const context = await browser.newContext({viewport:{width:1440,height:1050},deviceScaleFactor:1});
const page = await context.newPage();
const errors=[];
page.on('pageerror',e=>{errors.push(String(e));console.error('PAGE ERROR',e.message)});
page.on('console',m=>{if(m.type()==='error') console.error('CONSOLE',m.text().slice(0,240))});
await page.addInitScript(()=>{localStorage.setItem('aw-tour','1');localStorage.setItem('aw-theme','light');});
await page.goto('http://127.0.0.1:8000/app/atom-wind/');
await page.waitForFunction(()=>window.ATOM?.workspace,{timeout:45000});
await page.waitForTimeout(1800);
console.log('STATE',await page.evaluate(()=>window.ATOM.workspace.snapshot()));
await page.screenshot({path:`${out}/01-mon-vent-desktop.png`,fullPage:true});
await page.locator('a[data-v="carte3d"]').click();
await page.waitForFunction(()=>window.ATOM?.sceneStats,{timeout:30000});
await page.waitForTimeout(3500);
console.log('3D',await page.evaluate(()=>window.ATOM.sceneStats()));
await page.screenshot({path:`${out}/02-atmosphere-desktop.png`,fullPage:true});
await writeFile(`${out}/initial-inspection.json`,JSON.stringify({errors,state:await page.evaluate(()=>window.ATOM.workspace.snapshot()),scene:await page.evaluate(()=>window.ATOM.sceneStats())},null,2));
await browser.close();
